"""
dataset.py - Dataset preparation, validation, and data.yaml generation for YOLO11.
Interfaces with synth_pages synthetic output to provide an Ultralytics-compatible dataset:
  - Validates images and matching YOLO .txt label files.
  - Dynamically generates/updates data.yaml with resolved paths and 73 character names.
  - Runs bounding box validation (normalized range [0, 1], valid class IDs [0, 72]).
  - Summarizes split statistics (pages, boxes, density).

Usage:
  python -m yolo.dataset --config yolo/training.yaml
  python -m yolo.dataset --config yolo/training.yaml --verify
"""

import os
import sys
import argparse
import logging
from pathlib import Path
from typing import Dict, List, Any, Optional, Tuple
import yaml
import cv2

from .postprocess import build_charset_mapping

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(name)s: %(message)s"
)
logger = logging.getLogger("YOLODataset")


def load_config(config_path: str) -> Dict[str, Any]:
    path = Path(config_path)
    if not path.is_absolute() and not path.exists():
        alt_path = Path(__file__).resolve().parent / config_path
        if alt_path.exists():
            path = alt_path

    if not path.exists():
        raise FileNotFoundError(f"Configuration file not found: {config_path}")

    with open(path, "r", encoding="utf-8") as f:
        config = yaml.safe_load(f)
    return config


class YOLODatasetManager:
    """
    Manages and validates YOLO11 character detection dataset generated by synth_pages.
    """

    def __init__(self, config: Dict[str, Any]):
        self.config = config
        self.data_dir = self._resolve_path(config.get("paths", {}).get("data_dir", "../synth_pages/output/yolo"))
        self.data_yaml_path = self._resolve_output_yaml(config.get("paths", {}).get("data_yaml", "./data.yaml"))
        self.metadata_path = self._resolve_path(config.get("paths", {}).get("metadata_file", "../synth_pages/output/metadata.jsonl"))

        charset_cfg = config.get("charset", {})
        self.char_list, self.id_to_char = build_charset_mapping(charset_cfg)
        self.num_classes = len(self.char_list)

    def _resolve_path(self, path_str: str) -> Path:
        p = Path(path_str)
        if p.is_absolute() and p.exists():
            return p
        # Check relative to current working directory
        if p.exists():
            return p.resolve()
        # Check relative to module directory
        module_rel = (Path(__file__).resolve().parent / path_str).resolve()
        if module_rel.exists():
            return module_rel
        # Fallback to resolved relative path
        return p.resolve()

    def _resolve_output_yaml(self, path_str: str) -> Path:
        p = Path(path_str)
        if not p.is_absolute():
            p = (Path(__file__).resolve().parent / path_str).resolve()
        p.parent.mkdir(parents=True, exist_ok=True)
        return p

    def generate_data_yaml(self) -> Path:
        """
        Creates/updates the Ultralytics data.yaml file with resolved paths
        and complete 73 character class mappings.
        """
        images_dir = self.data_dir / "images"
        if not images_dir.exists():
            logger.warning(
                f"YOLO images directory not found at '{images_dir}'. "
                f"Ensure 'python synth_pages/build.py' has been run to generate data."
            )

        # Identify all test folders present in dataset
        test_folders = []
        if images_dir.exists():
            for folder in sorted(images_dir.iterdir()):
                if folder.is_dir() and folder.name.startswith("test"):
                    test_folders.append(f"images/{folder.name}")

        if not test_folders:
            # Fallback to configured defaults
            test_folders = [
                "images/test_seen_moderate",
                "images/test_unseen_fonts_moderate",
                "images/test_tiers_clean",
                "images/test_tiers_moderate",
                "images/test_tiers_hard"
            ]

        data = {
            "path": str(self.data_dir.resolve()),
            "train": "images/train",
            "val": "images/val",
            "test": test_folders,
            "names": {i: c for i, c in enumerate(self.char_list)}
        }

        with open(self.data_yaml_path, "w", encoding="utf-8") as f:
            yaml.safe_dump(data, f, sort_keys=False, allow_unicode=True)

        logger.info(f"Generated Ultralytics dataset configuration at: {self.data_yaml_path}")
        logger.info(f"  Dataset root: {self.data_dir.resolve()}")
        logger.info(f"  Total classes: {len(self.char_list)} non-space characters")
        return self.data_yaml_path

    def verify_dataset(self, check_samples: int = 50) -> Dict[str, Any]:
        """
        Performs thorough validation checks on YOLO annotations:
        1. Checks for orphaned images or labels.
        2. Validates normalized coordinate ranges: 0 <= cx, cy, w, h <= 1.
        3. Validates class IDs are within [0, num_classes - 1].
        4. Calculates box density and sample image sizes.
        """
        images_dir = self.data_dir / "images"
        labels_dir = self.data_dir / "labels"

        stats = {
            "total_images": 0,
            "total_labels": 0,
            "total_boxes": 0,
            "splits": {},
            "errors": []
        }

        if not images_dir.exists() or not labels_dir.exists():
            err_msg = f"Dataset directories missing. Looked in {self.data_dir}"
            logger.error(err_msg)
            stats["errors"].append(err_msg)
            return stats

        folders = [f.name for f in images_dir.iterdir() if f.is_dir()]
        logger.info(f"Found {len(folders)} folders in dataset: {folders}")

        for folder in sorted(folders):
            img_sub = images_dir / folder
            lab_sub = labels_dir / folder

            img_files = sorted(img_sub.glob("*.png"))
            lab_files = sorted(lab_sub.glob("*.txt")) if lab_sub.exists() else []

            folder_stats = {
                "images": len(img_files),
                "labels": len(lab_files),
                "boxes": 0
            }
            stats["total_images"] += len(img_files)
            stats["total_labels"] += len(lab_files)

            # Inspect label files
            sample_labs = lab_files[:check_samples] if check_samples else lab_files
            for lab_path in sample_labs:
                try:
                    with open(lab_path, "r", encoding="utf-8") as f:
                        lines = [line.strip() for line in f if line.strip()]
                    folder_stats["boxes"] += len(lines)
                    stats["total_boxes"] += len(lines)

                    for line_idx, line in enumerate(lines):
                        parts = line.split()
                        if len(parts) != 5:
                            stats["errors"].append(f"{lab_path.name}:{line_idx}: Invalid YOLO line format")
                            continue

                        cls_id = int(parts[0])
                        cx, cy, w, h = map(float, parts[1:])

                        if cls_id < 0 or cls_id >= self.num_classes:
                            stats["errors"].append(f"{lab_path.name}: Class ID {cls_id} out of bounds [0, {self.num_classes-1}]")

                        if not (0.0 <= cx <= 1.0 and 0.0 <= cy <= 1.0 and 0.0 <= w <= 1.0 and 0.0 <= h <= 1.0):
                            stats["errors"].append(f"{lab_path.name}: Box coordinates ({cx}, {cy}, {w}, {h}) out of range [0, 1]")
                except Exception as e:
                    stats["errors"].append(f"Error reading {lab_path}: {e}")

            stats["splits"][folder] = folder_stats
            logger.info(f"Split '{folder}': {len(img_files)} images, {len(lab_files)} labels, verified {folder_stats['boxes']} boxes.")

        if stats["errors"]:
            logger.warning(f"Validation encountered {len(stats['errors'])} errors! First 5: {stats['errors'][:5]}")
        else:
            logger.info("Dataset verification PASSED. All inspected YOLO annotations are valid.")

        return stats


def main():
    parser = argparse.ArgumentParser(description="Prepare and validate YOLO11 dataset from synth_pages output")
    parser.add_argument("--config", type=str, default="yolo/training.yaml", help="Path to yolo/training.yaml")
    parser.add_argument("--verify", action="store_true", help="Perform label syntax and bounding box verification")
    args = parser.parse_args()

    config = load_config(args.config)
    manager = YOLODatasetManager(config)

    yaml_path = manager.generate_data_yaml()
    print(f"Dataset YAML successfully prepared: {yaml_path}")

    if args.verify:
        stats = manager.verify_dataset()
        print(f"\nVerification Summary:")
        print(f"  Total Images: {stats['total_images']}")
        print(f"  Total Labels: {stats['total_labels']}")
        print(f"  Total Verified Boxes: {stats['total_boxes']}")
        print(f"  Errors Found: {len(stats['errors'])}")


if __name__ == "__main__":
    main()
